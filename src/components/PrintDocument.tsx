import { createPortal } from 'react-dom'
import type { CompanyProfile } from '@/types'

export function requestPrint() {
  document.body.classList.add('printing-document')
  const cleanup = () => document.body.classList.remove('printing-document')
  window.addEventListener('afterprint', cleanup, { once: true })
  window.setTimeout(async () => {
    const images = Array.from(document.querySelectorAll<HTMLImageElement>('#print-root img'))
    await Promise.all(images.map((image) => image.decode().catch(() => undefined)))
    window.print()
  }, 80)
  window.setTimeout(cleanup, 30_000)
}

export function PrintDocument({ company, logo, title, subtitle, columns, rows, total }: {
  company: CompanyProfile | null
  logo: string | null
  title: string
  subtitle?: string
  columns: string[]
  rows: string[][]
  total?: string
}) {
  const companyName = company?.name.trim() || 'Purchase Sale Office'
  const companyDetails = [
    company?.address.trim(),
    company?.phone.trim() ? `Phone: ${company.phone.trim()}` : '',
    company?.fiscalYear.trim() ? `Fiscal year: ${company.fiscalYear.trim()}` : '',
  ].filter((detail): detail is string => Boolean(detail))

  return createPortal(<div id="print-root" className="print-root" aria-hidden="true"><article className="print-sheet">
    <header className="print-company">
      <div className="print-brand">
        {logo && <img className="print-logo" src={logo} alt="" />}
        <div className="print-company-copy"><h1>{companyName}</h1>{companyDetails.length > 0 && <div className="print-company-details">{companyDetails.map((detail) => <span key={detail}>{detail}</span>)}</div>}</div>
      </div>
      <p className="print-date">Printed {new Date().toLocaleString()}</p>
    </header>
    <div className="print-document-heading"><h2>{title}</h2>{subtitle && <p>{subtitle}</p>}</div>
    <table className="print-table"><thead><tr>{columns.map((column) => <th key={column}>{column}</th>)}</tr></thead><tbody>{rows.map((row, index) => <tr key={index}>{row.map((value, cell) => <td key={cell}>{value || '—'}</td>)}</tr>)}</tbody></table>
    {total && <p className="print-total">Total: <strong>{total}</strong></p>}
    <footer className="print-footer">Generated by Purchase Sale Office · Verify totals against authorized source documents.</footer>
  </article></div>, document.body)
}
