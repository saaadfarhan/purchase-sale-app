test('database tools create a restorable backup, portable export, and integrity report', async (t) => {
  const directory = fs.mkdtempSync(path.join(os.tmpdir(), 'purchase-sale-tools-'))
  const source = path.join(directory, 'office.sqlite')
  const backup = path.join(directory, 'backup.sqlite')
  const store = openOfficeDatabase(source)
  t.after(() => { store.close(); fs.rmSync(directory, { recursive: true, force: true }) })

  store.saveAccount({ code: 'CASH', description: 'Cash in Hand' })
  store.createFirstUser({ username: 'admin', password: 'test-password' })
  const report = store.verifyDatabase()
  assert.equal(report.ok, true)
  assert.ok(report.tableCounts.accounts >= 1)

  const exported = store.exportData()
  assert.equal(exported.format, 'purchase-sale-office-data')
  assert.equal(exported.data.accounts[0].code, 'CASH')
  assert.equal(JSON.stringify(exported).includes('password_hash'), false, 'business export must not contain credential hashes')

  const result = await store.backupTo(backup)
  assert.equal(result.fileName, 'backup.sqlite')
  assert.ok(result.bytes > 0)
  const restored = new Database(backup, { readonly: true })
  assert.equal(restored.prepare('SELECT description FROM accounts WHERE code=?').get('CASH').description, 'Cash in Hand')
  assert.equal(restored.pragma('integrity_check')[0].integrity_check, 'ok')
  restored.close()
})

test('opening stock, stock types, and paired location transfers persist with safe validation', (t) => {
  const directory = fs.mkdtempSync(path.join(os.tmpdir(), 'purchase-sale-inventory-'))
  const store = openOfficeDatabase(path.join(directory, 'office.sqlite'))
  t.after(() => { store.close(); fs.rmSync(directory, { recursive: true, force: true }) })
  store.saveAccount({ code: 'P', description: 'Party' })
  store.saveItem({ code: 'I', description: 'Inventory item', unit: 'box', purchaseRate: 12, saleRate: 15, stockType: 'REG' })

  assert.deepEqual(store.addOpeningBalance({ itemCode: 'I', location: 'Main', quantity: 8 }), { itemCode: 'I', location: 'Main', quantity: 8, rate: 12, amount: 96 })
  assert.equal(store.listOpeningBalances().length, 1)
  assert.equal(store.getStock('I', 'Main'), 8)
  assert.throws(() => store.addOpeningBalance({ itemCode: 'I', location: 'Main', quantity: 0 }), /greater than zero/)

  const transfer = store.transferStock({ itemCode: 'I', fromLocation: 'Main', toLocation: 'Shop', quantity: 3 })
  assert.equal(transfer.transferId, 'TRF-00001')
  assert.equal(store.getStock('I', 'Main'), 5)
  assert.equal(store.getStock('I', 'Shop'), 3)
  assert.throws(() => store.transferStock({ itemCode: 'I', fromLocation: 'Main', toLocation: 'Shop', quantity: 6 }), /Insufficient stock/)
  assert.throws(() => store.transferStock({ itemCode: 'I', fromLocation: 'Main', toLocation: 'Main', quantity: 1 }), /must differ/)
  const transfers = store.listStockMovements().filter((movement) => movement.document === transfer.transferId)
  assert.equal(transfers.length, 2, 'transfer creates a matching outbound and inbound movement')
  assert.equal(transfers.reduce((sum, movement) => sum + movement.quantity, 0), 0, 'transfer preserves total stock')

  store.saveStockType({ code: 'FRZ', description: 'Frozen' })
  store.saveItem({ code: 'I-FRZ', description: 'Frozen item', unit: 'box', purchaseRate: 12, saleRate: 15, stockType: 'FRZ' })
  assert.throws(() => store.deleteStockType('FRZ'), /assigned to items/)
  store.saveStockType({ code: 'REG', description: 'Regular stock' })
  assert.throws(() => store.deleteStockType('REG'), /Built-in/)
  assert.throws(() => store.deleteStockType('SER'), /Built-in/)
  assert.throws(() => store.saveItem({ code: 'I', description: 'Inventory item', unit: 'box', purchaseRate: 12, saleRate: 15, stockType: 'NOPE' }), /stock type/)
})

test('SQLite voucher workflows validate balance, update atomically, and retain entry type', (t) => {
  const directory = fs.mkdtempSync(path.join(os.tmpdir(), 'purchase-sale-voucher-'))
  const store = openOfficeDatabase(path.join(directory, 'office.sqlite'))
  t.after(() => { store.close(); fs.rmSync(directory, { recursive: true, force: true }) })
  store.saveAccount({ code: 'CASH', description: 'Cash in Hand' })
  store.saveAccount({ code: 'PARTY', description: 'Party' })
  assert.equal(store.nextId('voucher'), 'VCH-00001')
  const voucher = { number: 'VCH-00001', date: '2026-10-19', type: 'PAYMENT', narration: 'Office payment', reference: 'PV-1', lines: [{ accountCode: 'PARTY', debit: 25, credit: 0 }, { accountCode: 'CASH', debit: 0, credit: 25 }] }
  assert.throws(() => store.saveVoucher({ ...voucher, lines: [{ accountCode: 'PARTY', debit: 25, credit: 0 }, { accountCode: 'CASH', debit: 0, credit: 20 }] }), /must balance/)
  assert.equal(store.listVouchers().length, 0, 'invalid posting leaves no header behind')
  store.saveVoucher(voucher)
  assert.equal(store.getVoucherType(voucher.number), 'PAYMENT')
  assert.equal(store.listVouchers(['PAYMENT']).length, 1)
  assert.equal(store.listVouchers(['RECEIPT']).length, 0)
  assert.throws(() => store.saveVoucher({ ...voucher, type: 'RECEIPT', update: true }), /cannot be changed/)
  store.saveVoucher({ ...voucher, narration: 'Updated payment', lines: [{ accountCode: 'PARTY', debit: 30, credit: 0 }, { accountCode: 'CASH', debit: 0, credit: 30 }], update: true })
  assert.equal(store.listVouchers()[0].lines[0].debit, 30)
  store.deleteVoucher(voucher.number)
  assert.equal(store.listVouchers().length, 0)
})

