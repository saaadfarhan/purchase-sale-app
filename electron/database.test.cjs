test('SQLite office store persists master data and posts stock atomically', (t) => {
  const directory = fs.mkdtempSync(path.join(os.tmpdir(), 'purchase-sale-'))
  const file = path.join(directory, 'office.sqlite')
  t.after(() => fs.rmSync(directory, { recursive: true, force: true }))

  const store = openOfficeDatabase(file)
  t.after(() => store.close())

  assert.equal(store.nextId('account'), 'ACC-00001')
  assert.equal(store.nextId('account'), 'ACC-00002', 'a reserved ID is not handed out twice')
  store.saveAccount({ code: 'ACC-00007', description: 'Existing imported account' })
  assert.equal(store.nextId('account'), 'ACC-00008', 'new IDs continue after imported matching IDs')
  assert.deepEqual(store.listLocations(), [], 'a clean database has no stock locations yet')

  store.saveAccount({ code: 'P-1', description: 'Party', openingBalance: 0 })
  store.saveAccount({ code: 'C-1', description: 'Customer', parentCode: 'P-1', openingBalance: 10 })
  assert.throws(() => store.saveAccount({ code: 'P-1', description: 'Party', parentCode: 'C-1', openingBalance: 0 }), /descendants/)
  store.saveItem({ code: 'I-1', description: 'Test item', unit: 'box', purchaseRate: 4, saleRate: 6, stockType: 'REG' })

  store.postChallan({ number: 'PUR-1', type: 'PURCHASE', date: '2026-10-19', party: 'C-1', location: 'Main', lines: [{ itemCode: 'I-1', quantity: 5 }] })
  assert.equal(store.getStock('I-1', 'Main'), 5)
  assert.throws(() => store.postChallan({ number: 'SAL-1', type: 'SALE', date: '2026-10-19', party: 'C-1', location: 'Main', lines: [{ itemCode: 'I-1', quantity: 6 }] }), /Insufficient stock/)
  assert.equal(store.listChallans().length, 1, 'failed sale must leave no challan header or lines')

  store.postChallan({ number: 'SAL-1', type: 'SALE', date: '2026-10-19', party: 'C-1', location: 'Main', lines: [{ itemCode: 'I-1', quantity: 2 }] })
  assert.equal(store.getStock('I-1', 'Main'), 3)
  assert.equal(store.getDashboard().stockQuantity, 3)
  assert.equal(store.listItems()[0].code, 'I-1')

  store.updateChallan({ number: 'PUR-1', type: 'PURCHASE', date: '2026-10-19', party: 'C-1', location: 'Main', lines: [{ itemCode: 'I-1', quantity: 4 }] })
  assert.equal(store.getStock('I-1', 'Main'), 2, 'purchase edit replaces its previous stock movement')
  assert.throws(() => store.updateChallan({ number: 'PUR-1', date: '2026-10-19', party: 'C-1', location: 'Main', lines: [{ itemCode: 'I-1', quantity: 1 }] }), /below zero stock/)
  assert.equal(store.getStock('I-1', 'Main'), 2, 'rejected update rolls back all partial changes')
  assert.equal(store.listChallans().find((row) => row.number === 'PUR-1').total, 16, 'rejected update preserves original document total')
  store.deleteChallan('SAL-1')
  assert.equal(store.getStock('I-1', 'Main'), 4, 'deleting a sale restores its stock movement')
  store.deleteChallan('PUR-1')
  assert.equal(store.getStock('I-1', 'Main'), 0, 'deleting a purchase with no dependent sales is allowed')
})

test('SQLite store refuses purchase deletion that would make remaining stock negative', (t) => {
  const directory = fs.mkdtempSync(path.join(os.tmpdir(), 'purchase-sale-stock-'))
  const store = openOfficeDatabase(path.join(directory, 'office.sqlite'))
  t.after(() => { store.close(); fs.rmSync(directory, { recursive: true, force: true }) })
  store.saveAccount({ code: 'P', description: 'Party' })
  store.saveItem({ code: 'I', description: 'Item', unit: 'pc', purchaseRate: 1, saleRate: 2, stockType: 'REG' })
  store.postChallan({ number: 'P-1', type: 'PURCHASE', date: '2026-10-19', party: 'P', location: 'Main', lines: [{ itemCode: 'I', quantity: 2 }] })
  store.postChallan({ number: 'S-1', type: 'SALE', date: '2026-10-19', party: 'P', location: 'Main', lines: [{ itemCode: 'I', quantity: 1 }] })
  assert.throws(() => store.deleteChallan('P-1'), /later sales would leave/)
  assert.equal(store.getStock('I', 'Main'), 1)
  assert.equal(store.listChallans().length, 2)
})

